alter table plan_days add column if not exists seq int default 0;

do $$
begin
  if exists (select 1 from pg_constraint where conname = 'plan_days_pkey'
             and conrelid = 'public.plan_days'::regclass) then
    alter table plan_days drop constraint plan_days_pkey;
  end if;
  if not exists (select 1 from pg_constraint where conname = 'plan_days_pkey'
                 and conrelid = 'public.plan_days'::regclass) then
    alter table plan_days add primary key (student_id, day, lane, seq);
  end if;
end $$;

